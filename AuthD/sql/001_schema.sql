-- AuthD PostgreSQL persistence schema.
--
-- Provenance classes used below:
--   [DONOR]   table/column exists in the lin2db.sql shipped beside the exact
--             L2Authd.exe/L2Authd.pdb pair.
--   [EXE]     state is required by a parameter/result contract observed in
--             the selected executable, even when the matching production
--             SQL deployment was not present in the archive.
--   [PORTABLE] PostgreSQL-owned persistence needed to implement that observed
--             contract without an MSSQL service.
--
-- The [PORTABLE] tables are kept outside recovered C++ class
-- layouts. They replace the missing database deployment, not product owners.

BEGIN;

CREATE SCHEMA IF NOT EXISTS authd;
SET search_path TO authd, public;

-- [DONOR] lin2db.sql tables -------------------------------------------------

CREATE TABLE IF NOT EXISTS banancheg (
    uid bigint NOT NULL DEFAULT 0,
    cid bigint NOT NULL DEFAULT 0,
    bid bigint NOT NULL DEFAULT 0,
    date timestamp without time zone NOT NULL,
    kicked boolean NOT NULL DEFAULT true
);

CREATE TABLE IF NOT EXISTS block_msg (
    uid integer,
    account varchar(14) NOT NULL,
    msg varchar(50),
    reason integer
);

CREATE INDEX IF NOT EXISTS block_msg_uid_idx ON block_msg (uid);

CREATE TABLE IF NOT EXISTS block_reason_code (
    block_reason integer PRIMARY KEY,
    block_desc varchar(50) NOT NULL,
    flag smallint
);

CREATE TABLE IF NOT EXISTS gm_illegal_login (
    account varchar(15) NOT NULL,
    try_date timestamp without time zone NOT NULL DEFAULT localtimestamp,
    ip varchar(15) NOT NULL
);

CREATE TABLE IF NOT EXISTS item_code (
    item_id integer PRIMARY KEY,
    name varchar(20) NOT NULL,
    duration integer NOT NULL,
    active_date timestamp without time zone NOT NULL
);

CREATE TABLE IF NOT EXISTS server (
    id smallint PRIMARY KEY,
    name varchar(25) NOT NULL,
    ip varchar(15) NOT NULL,
    inner_ip varchar(15) NOT NULL,
    age_limit smallint NOT NULL,
    pk_flag smallint NOT NULL,
    kind integer NOT NULL,
    port integer NOT NULL,
    region smallint NOT NULL DEFAULT 0,
    master_id integer,
    protocol integer,
    filter_id integer,
    test_mode integer,
    master_password bytea NOT NULL
        DEFAULT decode(repeat('00', 16), 'hex'),
    -- [EXE] The selected ReadServerListInfo binds this as result column 10.
    domain_name varchar(253) NOT NULL DEFAULT ''
);

CREATE TABLE IF NOT EXISTS ssn (
    ssn char(13) PRIMARY KEY,
    name varchar(15) NOT NULL,
    email varchar(50) NOT NULL,
    newsletter smallint NOT NULL DEFAULT 0,
    job integer NOT NULL,
    phone varchar(16) NOT NULL,
    mobile varchar(20),
    reg_date timestamp without time zone NOT NULL DEFAULT localtimestamp,
    zip varchar(6) NOT NULL,
    addr_main varchar(255) NOT NULL,
    addr_etc varchar(255) NOT NULL,
    account_num smallint NOT NULL DEFAULT 0,
    status_flag integer NOT NULL DEFAULT 0,
    final_news_date timestamp without time zone,
    master varchar(14),
    valid_email_date timestamp without time zone,
    final_master_date timestamp without time zone NOT NULL DEFAULT localtimestamp
);

CREATE TABLE IF NOT EXISTS user_account (
    uid integer GENERATED BY DEFAULT AS IDENTITY UNIQUE,
    account varchar(14) PRIMARY KEY,
    pay_stat smallint NOT NULL DEFAULT 0,
    login_flag integer NOT NULL DEFAULT 0,
    warn_flag integer NOT NULL DEFAULT 0,
    block_flag integer NOT NULL DEFAULT 0,
    block_flag2 integer NOT NULL DEFAULT 0,
    last_login timestamp without time zone,
    last_logout timestamp without time zone,
    subscription_flag integer NOT NULL DEFAULT 0,
    last_game integer,
    last_world integer,
    last_ip varchar(15),
    block_end_date timestamp without time zone,
    forbidden_servers bytea
        DEFAULT decode(repeat('00', 16), 'hex'),
    -- [EXE] Optional final ap_GStat output used by useDormantFlag.
    active_flag integer NOT NULL DEFAULT 0
);

CREATE TABLE IF NOT EXISTS user_auth (
    account varchar(14) PRIMARY KEY,
    password bytea NOT NULL
        DEFAULT decode(repeat('00', 16), 'hex'),
    quiz1 varchar(255) NOT NULL DEFAULT '',
    quiz2 varchar(255) NOT NULL DEFAULT '',
    answer1 bytea NOT NULL DEFAULT decode('11', 'hex'),
    answer2 bytea NOT NULL DEFAULT decode('11', 'hex'),
    md5password varchar(50),
    new_pwd_flag smallint DEFAULT 0,
    lastat timestamp without time zone,
    otp_flag smallint DEFAULT 0
);

CREATE TABLE IF NOT EXISTS user_block (
    block_date varchar(8) NOT NULL,
    account varchar(14) PRIMARY KEY
);

CREATE TABLE IF NOT EXISTS user_count (
    record_time timestamp without time zone NOT NULL DEFAULT localtimestamp,
    server_id smallint NOT NULL,
    world_user integer NOT NULL,
    limit_user integer NOT NULL,
    auth_user integer NOT NULL,
    wait_user integer NOT NULL,
    dayofweek integer NOT NULL
        DEFAULT extract(isodow FROM current_date)::integer
);

CREATE TABLE IF NOT EXISTS user_data (
    uid bigint PRIMARY KEY,
    user_char_num bigint NOT NULL,
    world varchar(20),
    char_name varchar(50) NOT NULL,
    char_id integer NOT NULL,
    account_name varchar(50) NOT NULL,
    lev smallint NOT NULL,
    create_date timestamp without time zone NOT NULL DEFAULT localtimestamp,
    use_time integer,
    subjob0_class integer NOT NULL DEFAULT -1,
    subjob1_class integer NOT NULL DEFAULT -1,
    subjob2_class integer NOT NULL DEFAULT -1,
    subjob3_class integer NOT NULL DEFAULT -1
);

CREATE TABLE IF NOT EXISTS user_info (
    account varchar(14) PRIMARY KEY,
    create_date timestamp without time zone NOT NULL DEFAULT localtimestamp,
    ssn varchar(13) NOT NULL,
    status_flag smallint NOT NULL DEFAULT 0,
    kind integer NOT NULL DEFAULT 0,
    ses_num varchar(12),
    getprizebox timestamp without time zone,
    ip varchar(20),
    mask_ip varchar(100),
    code varchar(10),
    ecode varchar(10),
    getprizebox1 timestamp without time zone,
    ip1 varchar(20),
    bsoeday_time_start timestamp without time zone
);

CREATE TABLE IF NOT EXISTS user_pay (
    start_date timestamp without time zone NOT NULL,
    account char(14) NOT NULL,
    end_date timestamp without time zone NOT NULL,
    uid bigint NOT NULL
);

CREATE TABLE IF NOT EXISTS user_stat (
    uid integer PRIMARY KEY,
    country varchar(4) NOT NULL,
    gender integer NOT NULL,
    birthyear varchar(4) NOT NULL
);

CREATE TABLE IF NOT EXISTS user_time (
    uid integer PRIMARY KEY,
    account varchar(14) NOT NULL,
    present_time integer NOT NULL,
    next_time integer,
    total_time integer NOT NULL,
    op_date timestamp without time zone NOT NULL,
    flag smallint NOT NULL
);

CREATE TABLE IF NOT EXISTS userno (
    uid integer
);

CREATE TABLE IF NOT EXISTS worldstatus (
    idx integer PRIMARY KEY,
    server varchar(50) NOT NULL,
    status smallint NOT NULL DEFAULT 0
);

-- [EXE]/[PORTABLE] current-procedure persistence ----------------------------

-- ap_GStatEtc/ap_SUserData expose a compact opaque user-data payload which is
-- unrelated to the donor's character-shaped user_data table.
CREATE TABLE IF NOT EXISTS account_etc (
    account varchar(14) PRIMARY KEY,
    security_card integer NOT NULL DEFAULT 0,
    user_data bytea,
    user_data_length smallint NOT NULL DEFAULT 0
);

CREATE TABLE IF NOT EXISTS account_game_slot (
    uid integer PRIMARY KEY,
    last_logout_time timestamp without time zone,
    activate_time timestamp without time zone,
    activate_information bytea NOT NULL
        DEFAULT decode(repeat('00', 8), 'hex')
);

CREATE TABLE IF NOT EXISTS account_game_character (
    uid integer NOT NULL,
    server_id smallint NOT NULL,
    character_id integer NOT NULL,
    level integer NOT NULL,
    updated_at timestamp without time zone NOT NULL DEFAULT localtimestamp,
    PRIMARY KEY (uid, server_id, character_id)
);

-- The current BanAccount call returns both the account text and a generated
-- restriction number. Neither exists in the donor block_msg layout.
CREATE TABLE IF NOT EXISTS account_restriction (
    restriction_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    uid integer NOT NULL,
    account varchar(14) NOT NULL,
    restriction_kind smallint NOT NULL,
    message varchar(50),
    created_at timestamp without time zone NOT NULL DEFAULT localtimestamp
);

CREATE INDEX IF NOT EXISTS account_restriction_uid_idx
    ON account_restriction (uid, restriction_id DESC);

-- The selected call adds a literal category/reason argument absent from the
-- older donor procedure.
CREATE TABLE IF NOT EXISTS illegal_login_trace (
    trace_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    uid integer NOT NULL,
    ip varchar(15) NOT NULL,
    reason integer NOT NULL,
    try_date timestamp without time zone NOT NULL DEFAULT localtimestamp
);

CREATE TABLE IF NOT EXISTS service_time_schedule (
    portal_uid integer NOT NULL,
    game_id smallint NOT NULL,
    result integer NOT NULL DEFAULT 0,
    schedule varchar(48) NOT NULL
        DEFAULT repeat('F', 48),
    PRIMARY KEY (portal_uid, game_id)
);

CREATE TABLE IF NOT EXISTS fatigue_account (
    uid integer PRIMARY KEY,
    play_time integer NOT NULL DEFAULT 0,
    last_logout_time integer NOT NULL DEFAULT 0,
    updated_at timestamp without time zone NOT NULL DEFAULT localtimestamp
);

CREATE TABLE IF NOT EXISTS fatigue_customer (
    fcid integer PRIMARY KEY,
    total_time integer NOT NULL DEFAULT 0,
    last_logout_time integer NOT NULL DEFAULT 0,
    updated_at timestamp without time zone NOT NULL DEFAULT localtimestamp
);

CREATE TABLE IF NOT EXISTS zone_fatigue_configuration (
    zone smallint PRIMARY KEY,
    capsule_count smallint NOT NULL,
    capsule_ids bytea NOT NULL,
    capsule_time_amounts bytea NOT NULL,
    reset_at timestamp without time zone NOT NULL DEFAULT localtimestamp
);

CREATE TABLE IF NOT EXISTS zone_fatigue_state (
    account_id integer NOT NULL,
    zone smallint NOT NULL,
    remain_time integer NOT NULL DEFAULT 0,
    capsule_used_flags bytea NOT NULL DEFAULT ''::bytea,
    capsule_last_used_at timestamp without time zone,
    recent_reset_at timestamp without time zone NOT NULL DEFAULT localtimestamp,
    PRIMARY KEY (account_id, zone)
);

-- Test-server procedure owners are distinct in the selected call sites even
-- though the paired donor dump does not include their deployment tables.
CREATE TABLE IF NOT EXISTS worldstatus_test (
    idx integer PRIMARY KEY,
    server varchar(50) NOT NULL,
    status smallint NOT NULL DEFAULT 0
);

COMMIT;
