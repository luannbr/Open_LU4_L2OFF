"""Writes PledgeSkillInfo.xml from the GF clan skills (skillacquire.txt pledge_begin).

usage: python gen_pledgeskill.py <GF skillacquire.txt> <converted skilldata.txt> <output xml> <report>

GF clan leaders bought clan skills from an NPC with clan reputation and items.
This server dropped that window (UserSocket: legacy clan acquire type) and adds
clan skills itself: AUTO skills when the clan reaches their level, SYSTEM skills
when a residence grants them (castledata residence_skill_list). Its MANUAL type
is a timed seal that the client lists from its own data, so GF skills cannot
use it. The GF skills therefore become:
  regular clan skills -> AUTO at the GF clan level (get_lv), free;
  residence_skill     -> SYSTEM.
The member rank (social_class) keeps its GF number; this server names the same
numbers WANDERER..EMPEROR. Squad skills (sub_pledge_begin) have no counterpart:
this server applies clan skills to the whole clan. The report lists what is lost.
"""
import os
import re
import sys

source, skilldata, target, report = sys.argv[1:5]

SOCIAL_CLASS = ["WANDERER", "SQUIRE", "MERCENARY", "KNIGHT", "BANNERET",
                "BARON", "COUNT", "DUKE", "KING", "EMPEROR"]

known = set()
for line in open(skilldata, encoding="utf-16"):
    match = re.search(r"skill_name\s*=\s*\[([^\]]+)\]", line)
    if match:
        known.add(match.group(1))

text = open(source, encoding="utf-16").read()
def section(name):
    match = re.search(rf"^{name}_begin(.*?)^{name}_end", text, re.S | re.M)
    return match.group(1) if match else ""

def field(line, name):
    match = re.search(rf"\b{name}\s*=\s*(\S+)", line)
    return match.group(1) if match else None

entries, lost = [], []
for line in section("pledge").splitlines():
    if "skill_begin" not in line:
        continue
    name = field(line, "skill_name").strip("[]")
    level = int(field(line, "get_lv"))
    cost = int(field(line, "lv_up_sp"))
    items = re.search(r"item_needed\s*=\s*(\{.*?\})\s+social_class", line).group(1)
    social = int(field(line, "social_class"))
    residence = field(line, "residence_skill") == "true"
    if name not in known:
        lost.append(f"[{name}]: not in skilldata, left out")
        continue
    if residence:
        entries.append((name, "SYSTEM", social, 0))
    else:
        entries.append((name, "AUTO", social, level))
        if cost or items != "{}":
            lost.append(f"[{name}]: GF cost {cost} clan reputation and items {items}; now free at clan level {level}")

for line in section("sub_pledge").splitlines():
    if "skill_begin" in line:
        lost.append(f"[{field(line, 'skill_name').strip('[]')}]: squad skill ({field(line, 'pledge_type')}), left out")

rows = ['<?xml version="1.0" encoding="utf-16"?>',
        '<PledgeSkillInfo xmlns:xsi="http://www.w3.org/2001/XMLSchema-instance" xmlns="urn:L2PledgeInfo" '
        'xsi:schemaLocation="urn:L2PledgeInfo PledgeInfo.xsd">',
        "\t<!-- Generated by tools/gfport/gen_pledgeskill.py from the GF skillacquire.txt (pledge_begin). -->"]
for name, add_type, social, level in entries:
    rows += [f'\t<Skill name_id="{name}" add_type="{add_type}" social_class="{SOCIAL_CLASS[social]}">',
             f'\t\t<Condition level="{level}"/>',
             '\t\t<Cost name_value="0"/>',
             "\t</Skill>"]
rows.append("</PledgeSkillInfo>")
open(target, "w", encoding="utf-16", newline="").write("\r\n".join(rows) + "\r\n")
os.makedirs(os.path.dirname(report), exist_ok=True)
open(report, "w", encoding="utf-8", newline="\n").write("\n".join(lost) + "\n")
auto = sum(1 for entry in entries if entry[1] == "AUTO")
print(f"{auto} AUTO and {len(entries) - auto} SYSTEM clan skills; {len(lost)} notes (see {os.path.basename(report)})")
