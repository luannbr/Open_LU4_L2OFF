BEGIN;

CREATE SCHEMA IF NOT EXISTS "community";

CREATE TABLE "community"."user_memo" (
    "world_id" integer NOT NULL,
    "char_id" integer NOT NULL,
    "char_name" character varying(64) NOT NULL,
    "account_id" integer NOT NULL,
    "account_name" character varying(64) NOT NULL,
    "memo_id" integer GENERATED BY DEFAULT AS IDENTITY
        (START WITH 1 INCREMENT BY 1) NOT NULL,
    "memo_title" character varying(128) NOT NULL,
    "memo_text" character varying(4000) NOT NULL,
    "insert_time" timestamp without time zone
        DEFAULT "world"."mssql_getdate"() NOT NULL,
    "deleted" smallint DEFAULT 0 NOT NULL
);

CREATE INDEX "ix_user_memo"
    ON "community"."user_memo" (
        "world_id",
        "char_id",
        "account_id",
        "memo_id"
    );

CREATE OR REPLACE FUNCTION "community"."lin_creatememo"(
    p_world_id integer,
    p_char_id integer,
    p_char_name text,
    p_account_id integer,
    p_account_name text,
    p_memo_title text,
    p_memo_text text
) RETURNS TABLE (memo_id integer)
LANGUAGE plpgsql
VOLATILE
AS $function$
DECLARE
    v_memo_count integer;
    v_memo_id integer;
BEGIN
    SELECT count(*)::integer
    INTO v_memo_count
    FROM "community"."user_memo"
    WHERE "user_memo"."account_id" = p_account_id
      AND "user_memo"."deleted" = 0;

    IF v_memo_count > 100 THEN
        RETURN QUERY SELECT -1;
        RETURN;
    END IF;

    INSERT INTO "community"."user_memo" (
        "world_id",
        "char_id",
        "char_name",
        "account_id",
        "account_name",
        "memo_title",
        "memo_text"
    ) VALUES (
        p_world_id,
        p_char_id,
        p_char_name,
        p_account_id,
        p_account_name,
        p_memo_title,
        p_memo_text
    )
    RETURNING "user_memo"."memo_id"
    INTO v_memo_id;

    RETURN QUERY SELECT v_memo_id;
END;
$function$;

CREATE OR REPLACE FUNCTION "community"."lin_deletememo"(
    p_memo_id integer,
    p_delete integer
) RETURNS void
LANGUAGE plpgsql
VOLATILE
AS $function$
BEGIN
    UPDATE "community"."user_memo"
    SET "deleted" =
        CASE WHEN p_delete = 1 THEN 1 ELSE 0 END
    WHERE "user_memo"."memo_id" = p_memo_id;
END;
$function$;

CREATE OR REPLACE FUNCTION "community"."lin_getmemo"(
    p_memo_id integer
) RETURNS TABLE (
    world_id integer,
    insert_time integer,
    char_id integer,
    char_name text,
    account_id integer,
    account_name text,
    memo_title text,
    memo_text text
)
LANGUAGE sql
STABLE
AS $function$
    SELECT
        memo."world_id",
        extract(epoch FROM (
            date_trunc('second', memo."insert_time") -
            timestamp '1970-01-01 00:00:00'
        ))::integer,
        memo."char_id",
        memo."char_name"::text,
        memo."account_id",
        memo."account_name"::text,
        memo."memo_title"::text,
        memo."memo_text"::text
    FROM "community"."user_memo" AS memo
    WHERE memo."memo_id" = p_memo_id
      AND memo."deleted" = 0;
$function$;

CREATE OR REPLACE FUNCTION "community"."lin_getmemolist"(
    p_account_id integer,
    p_search text
) RETURNS TABLE (
    memo_id integer,
    world_id integer,
    insert_time integer,
    char_id integer,
    char_name text,
    account_id integer,
    account_name text,
    memo_title text,
    memo_count integer
)
LANGUAGE sql
STABLE
AS $function$
    SELECT
        memo."memo_id",
        memo."world_id",
        extract(epoch FROM (
            date_trunc('second', memo."insert_time") -
            timestamp '1970-01-01 00:00:00'
        ))::integer,
        memo."char_id",
        memo."char_name"::text,
        memo."account_id",
        memo."account_name"::text,
        memo."memo_title"::text,
        count(*) OVER ()::integer
    FROM "community"."user_memo" AS memo
    WHERE memo."account_id" = p_account_id
      AND memo."deleted" = 0
      AND (
          char_length(rtrim(p_search)) = 0 OR
          lower(memo."memo_title") LIKE '%' || lower(p_search) || '%'
      )
    ORDER BY memo."insert_time" DESC;
$function$;

CREATE OR REPLACE FUNCTION "community"."lin_updatememo"(
    p_memo_id integer,
    p_memo_title text,
    p_memo_text text
) RETURNS void
LANGUAGE sql
VOLATILE
AS $function$
    UPDATE "community"."user_memo"
    SET "memo_title" = p_memo_title,
        "memo_text" = p_memo_text
    WHERE "user_memo"."memo_id" = p_memo_id;
$function$;

COMMIT;
