-- Current Cached.exe RQ_EX slots 25-27 pledge-emblem persistence.
--
-- The image fixes all four callable names, input arities and result columns.
-- Classic 3.0, modified 287 and Ertheia keep the preceding
-- pledge_emblem lifecycle: one row per pledge, a generated emblem ID and a
-- fifteen-minute registration cooldown.  The current FileServer path stores
-- a download URL instead of the old bitmap.  No supplied database source
-- keeps that current physical relation name, so the table below is named
-- as portable persistence. It is not claimed as original DDL.

BEGIN;

CREATE SCHEMA IF NOT EXISTS "world";

CREATE TABLE "world"."cached_portable_pledge_new_emblem" (
    "pledge_emblem_id" integer
        GENERATED BY DEFAULT AS IDENTITY
        (START WITH 1 INCREMENT BY 1) NOT NULL,
    "pledge_id" integer NOT NULL,
    "url" text NOT NULL,
    "created_date" timestamp without time zone
        DEFAULT "world"."mssql_getdate"() NOT NULL,
    CONSTRAINT "pk_cached_portable_pledge_new_emblem"
        PRIMARY KEY ("pledge_emblem_id"),
    CONSTRAINT "uq_cached_portable_pledge_new_emblem_pledge"
        UNIQUE ("pledge_id")
);

CREATE OR REPLACE FUNCTION "world"."lin_canregisterpledgenewemblem"(
    p_pledge_id integer
) RETURNS TABLE (result integer)
LANGUAGE sql
STABLE
AS $function$
    SELECT CASE
        WHEN max(emblem."created_date") IS NULL
          OR "world"."mssql_getdate"() - max(emblem."created_date") >=
             interval '15 minutes'
        THEN 0
        ELSE -1
    END::integer
      FROM "world"."cached_portable_pledge_new_emblem" AS emblem
     WHERE emblem."pledge_id" = p_pledge_id;
$function$;

CREATE OR REPLACE FUNCTION "world"."lin_initpledgenewemblem"(
    p_pledge_id integer
) RETURNS void
LANGUAGE plpgsql
VOLATILE
AS $function$
BEGIN
    UPDATE "world"."pledge" AS pledge
       SET "new_emblem_id" = 0
     WHERE pledge."pledge_id" = p_pledge_id;

    DELETE FROM "world"."cached_portable_pledge_new_emblem" AS emblem
     WHERE emblem."pledge_id" = p_pledge_id;
END;
$function$;

CREATE OR REPLACE FUNCTION "world"."lin_loadpledgenewemblem"(
    p_pledge_emblem_id integer
) RETURNS TABLE (url text)
LANGUAGE sql
STABLE
AS $function$
    SELECT emblem."url"
      FROM "world"."cached_portable_pledge_new_emblem" AS emblem
     WHERE emblem."pledge_emblem_id" = p_pledge_emblem_id;
$function$;

CREATE OR REPLACE FUNCTION "world"."lin_setpledgenewemblem"(
    p_pledge_id integer,
    p_url text
) RETURNS TABLE (pledge_emblem_id integer)
LANGUAGE plpgsql
VOLATILE
AS $function$
DECLARE
    v_pledge_emblem_id integer;
BEGIN
    DELETE FROM "world"."cached_portable_pledge_new_emblem" AS emblem
     WHERE emblem."pledge_id" = p_pledge_id;

    INSERT INTO "world"."cached_portable_pledge_new_emblem" AS inserted (
        "pledge_id",
        "url"
    ) VALUES (
        p_pledge_id,
        p_url
    )
    RETURNING inserted."pledge_emblem_id"
         INTO v_pledge_emblem_id;

    -- The current process makes no second SQL call and does not mutate its
    -- in-memory CPledge here.  Persisting the returned ID on pledge is thus a
    -- required observable effect of the current two-input procedure.
    UPDATE "world"."pledge" AS pledge
       SET "new_emblem_id" = v_pledge_emblem_id
     WHERE pledge."pledge_id" = p_pledge_id;

    RETURN QUERY SELECT v_pledge_emblem_id;
END;
$function$;

COMMIT;
