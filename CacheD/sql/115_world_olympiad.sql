CREATE OR REPLACE FUNCTION "world"."lin_wolympiadnominateheroes"(
    p_now_season integer,
    p_new_step integer,
    p_new_season_start_time double precision,
    p_nominate_heroes integer
) RETURNS TABLE (
    new_season integer,
    legendary_id integer
)
LANGUAGE plpgsql
VOLATILE
AS $function$
DECLARE
    v_new_season integer;
    v_legendary_id integer := 0;
BEGIN
    DELETE FROM "world"."world_olympiad_result" AS result
    WHERE result."season" = p_now_season;

    WITH eligible AS (
        SELECT participant.*
        FROM "world"."world_olympiad_user" AS participant
        WHERE participant."match_count" >= 10
    ), ranked AS (
        SELECT eligible.*,
               ROW_NUMBER() OVER (
                   ORDER BY eligible."olympiad_point" DESC,
                            eligible."olympiad_win_count" DESC,
                            eligible."match_count" DESC,
                            eligible."world_id",
                            eligible."user_db_id"
               )::integer AS "ranking",
               ROW_NUMBER() OVER (
                   PARTITION BY eligible."hero_class_type"
                   ORDER BY eligible."olympiad_point" DESC,
                            eligible."olympiad_win_count" DESC,
                            eligible."match_count" DESC,
                            eligible."world_id",
                            eligible."user_db_id"
               )::integer AS "class_ranking",
               ROW_NUMBER() OVER (
                   PARTITION BY eligible."world_id",
                                eligible."hero_class_type"
                   ORDER BY eligible."olympiad_point" DESC,
                            eligible."olympiad_win_count" DESC,
                            eligible."match_count" DESC,
                            eligible."user_db_id"
               )::integer AS "server_class_ranking"
        FROM eligible
    )
    INSERT INTO "world"."world_olympiad_result" (
        "season", "world_id", "user_db_id", "hero_class_type",
        "char_name", "point", "match_count", "win_count", "lose_count",
        "ranking", "class_ranking", "server_class_ranking"
    )
    SELECT p_now_season,
           ranked."world_id",
           ranked."user_db_id",
           ranked."hero_class_type",
           ranked."char_name",
           ranked."olympiad_point",
           ranked."match_count",
           ranked."olympiad_win_count",
           ranked."olympiad_lose_count",
           ranked."ranking",
           ranked."class_ranking",
           ranked."server_class_ranking"
    FROM ranked;

    UPDATE "world"."world_olympiad_user" SET "hero_type" = 0;
    IF p_nominate_heroes <> 0 THEN
        UPDATE "world"."world_olympiad_user" AS participant
        SET "hero_type" = 1,
            "win_count" = participant."win_count" + 1
        FROM "world"."world_olympiad_result" AS result
        WHERE result."season" = p_now_season
          AND result."class_ranking" = 1
          AND participant."world_id" = result."world_id"
          AND participant."user_db_id" = result."user_db_id";

        SELECT result."user_db_id"
        INTO v_legendary_id
        FROM "world"."world_olympiad_result" AS result
        WHERE result."season" = p_now_season
        ORDER BY result."ranking"
        LIMIT 1;
        v_legendary_id := COALESCE(v_legendary_id, 0);
    END IF;

    UPDATE "world"."world_olympiad_user" AS participant
    SET "previous_point" = participant."olympiad_point",
        "olympiad_point" = 0,
        "match_count" = 0,
        "olympiad_win_count" = 0,
        "olympiad_lose_count" = 0;

    INSERT INTO "world"."olympiad" (
        "step", "season_start_time", "legendary_id"
    ) VALUES (
        p_new_step,
        p_new_season_start_time::integer,
        v_legendary_id
    ) RETURNING "season" INTO v_new_season;

    RETURN QUERY SELECT v_new_season, v_legendary_id;
END;
$function$;

