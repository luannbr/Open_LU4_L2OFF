CREATE OR REPLACE FUNCTION "world"."lin_wolympiadload"()
RETURNS TABLE (
    season integer,
    step integer,
    season_start_time integer,
    start_sec integer,
    bonus1_sec integer,
    bonus2_sec integer,
    bonus3_sec integer,
    bonus4_sec integer,
    nominate_sec integer,
    legendary_id integer
)
LANGUAGE plpgsql
VOLATILE
AS $function$
BEGIN
    IF NOT EXISTS (SELECT 1 FROM "world"."olympiad") THEN
        INSERT INTO "world"."olympiad" ("step") VALUES (0);
    END IF;

    RETURN QUERY
    SELECT olympiad."season",
           COALESCE(olympiad."step", 0),
           COALESCE(olympiad."season_start_time", 0),
           COALESCE(olympiad."start_sec", 0),
           COALESCE(olympiad."bonus1_sec", 0),
           COALESCE(olympiad."bonus2_sec", 0),
           COALESCE(olympiad."bonus3_sec", 0),
           COALESCE(olympiad."bonus4_sec", 0),
           COALESCE(olympiad."nominate_sec", 0),
           olympiad."legendary_id"
    FROM "world"."olympiad" AS olympiad
    ORDER BY olympiad."season" DESC
    LIMIT 1;
END;
$function$;

