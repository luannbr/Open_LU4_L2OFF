CREATE OR REPLACE FUNCTION "world"."lin_wolympiadgetrecord"(
    p_world_id integer,
    p_user_db_id integer,
    p_season integer
) RETURNS TABLE (
    point integer,
    win_count integer,
    lose_count integer,
    previous_class_type integer,
    previous_rank integer,
    previous_rank_count integer,
    previous_class_rank integer,
    previous_class_rank_count integer,
    previous_server_class_rank integer,
    previous_server_class_rank_count integer,
    previous_point integer,
    previous_win_count integer,
    previous_lose_count integer
)
LANGUAGE sql
STABLE
AS $function$
    WITH previous AS (
        SELECT result.*,
               COUNT(*) OVER ()::integer AS "rank_count",
               COUNT(*) OVER (
                   PARTITION BY result."hero_class_type"
               )::integer AS "class_rank_count",
               COUNT(*) OVER (
                   PARTITION BY result."world_id",
                                result."hero_class_type"
               )::integer AS "server_class_rank_count"
        FROM "world"."world_olympiad_result" AS result
        WHERE result."season" = p_season - 1
    )
    SELECT participant."olympiad_point",
           participant."olympiad_win_count",
           participant."olympiad_lose_count",
           COALESCE(previous."hero_class_type", 0),
           COALESCE(previous."ranking", 0),
           COALESCE(previous."rank_count", 0),
           COALESCE(previous."class_ranking", 0),
           COALESCE(previous."class_rank_count", 0),
           COALESCE(previous."server_class_ranking", 0),
           COALESCE(previous."server_class_rank_count", 0),
           COALESCE(previous."point", 0),
           COALESCE(previous."win_count", 0),
           COALESCE(previous."lose_count", 0)
    FROM "world"."world_olympiad_user" AS participant
    LEFT JOIN previous
      ON previous."world_id" = participant."world_id"
     AND previous."user_db_id" = participant."user_db_id"
    WHERE participant."world_id" = p_world_id
      AND participant."user_db_id" = p_user_db_id;
$function$;

CREATE OR REPLACE FUNCTION "world"."lin_wolympiadgeneraterecord_fortest"(
    p_max_olympiad_point integer,
    p_max_olympiad_win_count integer,
    p_max_olympiad_match_count integer
) RETURNS void
LANGUAGE plpgsql
VOLATILE
AS $function$
DECLARE
    v_season integer;
BEGIN
    SELECT olympiad."season"
    INTO v_season
    FROM "world"."olympiad" AS olympiad
    ORDER BY olympiad."season" DESC
    LIMIT 1;
    IF v_season IS NULL THEN
        RETURN;
    END IF;

    DELETE FROM "world"."world_olympiad_result" AS result
    WHERE result."season" = v_season;
    WITH bounded AS (
        SELECT participant."world_id",
               participant."user_db_id",
               participant."hero_class_type",
               participant."char_name",
               LEAST(
                   participant."olympiad_point",
                   GREATEST(p_max_olympiad_point, 0)
               ) AS "point",
               LEAST(
                   participant."match_count",
                   GREATEST(p_max_olympiad_match_count, 0)
               ) AS "match_count",
               LEAST(
                   participant."olympiad_win_count",
                   GREATEST(p_max_olympiad_win_count, 0)
               ) AS "win_count",
               participant."olympiad_lose_count" AS "lose_count"
        FROM "world"."world_olympiad_user" AS participant
    ), ranked AS (
        SELECT bounded.*,
               ROW_NUMBER() OVER (
                   ORDER BY bounded."point" DESC,
                            bounded."win_count" DESC,
                            bounded."match_count" DESC,
                            bounded."world_id",
                            bounded."user_db_id"
               )::integer AS "ranking",
               ROW_NUMBER() OVER (
                   PARTITION BY bounded."hero_class_type"
                   ORDER BY bounded."point" DESC,
                            bounded."win_count" DESC,
                            bounded."match_count" DESC,
                            bounded."world_id",
                            bounded."user_db_id"
               )::integer AS "class_ranking",
               ROW_NUMBER() OVER (
                   PARTITION BY bounded."world_id",
                                bounded."hero_class_type"
                   ORDER BY bounded."point" DESC,
                            bounded."win_count" DESC,
                            bounded."match_count" DESC,
                            bounded."user_db_id"
               )::integer AS "server_class_ranking"
        FROM bounded
    )
    INSERT INTO "world"."world_olympiad_result" (
        "season", "world_id", "user_db_id", "hero_class_type",
        "char_name", "point", "match_count", "win_count", "lose_count",
        "ranking", "class_ranking", "server_class_ranking"
    )
    SELECT v_season,
           ranked."world_id",
           ranked."user_db_id",
           ranked."hero_class_type",
           ranked."char_name",
           ranked."point",
           ranked."match_count",
           ranked."win_count",
           ranked."lose_count",
           ranked."ranking",
           ranked."class_ranking",
           ranked."server_class_ranking"
    FROM ranked;
END;
$function$;

