CREATE OR REPLACE FUNCTION "world"."lin_wolympiadsaverecord"(
    p_season integer,
    p_step integer,
    p_winner_world_id integer,
    p_winner_db_id integer,
    p_loser_world_id integer,
    p_loser_db_id integer,
    p_winner_point integer,
    p_winner_item_type integer,
    p_winner_item_amount integer,
    p_loser_point integer,
    p_loser_item_type integer,
    p_loser_item_amount integer,
    p_time integer,
    p_result_type integer,
    p_elapsed_time integer,
    p_game_rule integer
) RETURNS void
LANGUAGE plpgsql
VOLATILE
AS $function$
BEGIN
    INSERT INTO "world"."world_olympiad_match" (
        "season", "step", "winner_world_id", "winner_db_id",
        "loser_world_id", "loser_db_id", "winner_point",
        "winner_item_type", "winner_item_amount", "loser_point",
        "loser_item_type", "loser_item_amount", "match_time",
        "result_type", "elapsed_time", "game_rule"
    ) VALUES (
        p_season, p_step, p_winner_world_id, p_winner_db_id,
        p_loser_world_id, p_loser_db_id, p_winner_point,
        p_winner_item_type, p_winner_item_amount, p_loser_point,
        p_loser_item_type, p_loser_item_amount, p_time,
        p_result_type, p_elapsed_time, p_game_rule
    );

    IF p_result_type = 1 THEN
        IF p_winner_db_id <> 0 THEN
            UPDATE "world"."world_olympiad_user" AS participant
            SET "olympiad_point" = GREATEST(
                    0, participant."olympiad_point" + p_winner_point),
                "match_count" = participant."match_count" + 1
            WHERE participant."world_id" = p_winner_world_id
              AND participant."user_db_id" = p_winner_db_id;
        END IF;
        IF p_loser_db_id <> 0 THEN
            UPDATE "world"."world_olympiad_user" AS participant
            SET "olympiad_point" = GREATEST(
                    0, participant."olympiad_point" + p_loser_point),
                "match_count" = participant."match_count" + 1
            WHERE participant."world_id" = p_loser_world_id
              AND participant."user_db_id" = p_loser_db_id;
        END IF;
    ELSIF p_result_type = 2 THEN
        IF p_loser_db_id <> 0 THEN
            UPDATE "world"."world_olympiad_user" AS participant
            SET "olympiad_point" = GREATEST(
                    0, participant."olympiad_point" + p_loser_point)
            WHERE participant."world_id" = p_loser_world_id
              AND participant."user_db_id" = p_loser_db_id;
        END IF;
    ELSE
        IF p_winner_db_id <> 0 THEN
            UPDATE "world"."world_olympiad_user" AS participant
            SET "olympiad_point" = GREATEST(
                    0, participant."olympiad_point" + p_winner_point),
                "match_count" = participant."match_count" + 1,
                "olympiad_win_count" =
                    participant."olympiad_win_count" + 1
            WHERE participant."world_id" = p_winner_world_id
              AND participant."user_db_id" = p_winner_db_id;
        END IF;
        IF p_loser_db_id <> 0 THEN
            UPDATE "world"."world_olympiad_user" AS participant
            SET "olympiad_point" = GREATEST(
                    0, participant."olympiad_point" + p_loser_point),
                "match_count" = participant."match_count" + 1,
                "olympiad_lose_count" =
                    participant."olympiad_lose_count" + 1
            WHERE participant."world_id" = p_loser_world_id
              AND participant."user_db_id" = p_loser_db_id;
        END IF;
    END IF;
END;
$function$;

