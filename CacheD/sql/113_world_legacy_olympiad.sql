CREATE OR REPLACE FUNCTION "world"."lin_loadolympiad"()
RETURNS TABLE (
    season integer,
    step integer,
    season_start_time integer,
    start_sec integer,
    bonus1_sec integer,
    bonus2_sec integer,
    bonus3_sec integer,
    bonus4_sec integer,
    nominate_sec integer
)
LANGUAGE plpgsql
VOLATILE
AS $function$
BEGIN
    IF NOT EXISTS (SELECT 1 FROM "world"."olympiad") THEN
        INSERT INTO "world"."olympiad" ("step") VALUES (0);
    END IF;

    RETURN QUERY
    SELECT olympiad."season",
           olympiad."step",
           COALESCE(olympiad."season_start_time", 0),
           COALESCE(olympiad."start_sec", 0),
           COALESCE(olympiad."bonus1_sec", 0),
           COALESCE(olympiad."bonus2_sec", 0),
           COALESCE(olympiad."bonus3_sec", 0),
           COALESCE(olympiad."bonus4_sec", 0),
           COALESCE(olympiad."nominate_sec", 0)
    FROM "world"."olympiad" AS olympiad
    ORDER BY olympiad."season" DESC
    LIMIT 1;
END;
$function$;

CREATE OR REPLACE FUNCTION "world"."lin_getpledgegame"(
    p_season integer DEFAULT 0
) RETURNS TABLE (
    season integer,
    step integer,
    season_start_time integer,
    max_prize integer,
    previous_winner_pledge_id integer,
    previous_winner_pledge_name text,
    previous_winner_character_id integer,
    previous_winner_character_name text,
    previous_winner_got_item integer
)
LANGUAGE plpgsql
VOLATILE
AS $function$
BEGIN
    IF NOT EXISTS (SELECT 1 FROM "world"."pledge_game") THEN
        INSERT INTO "world"."pledge_game" (
            "season",
            "step",
            "season_start_time"
        ) VALUES (
            1,
            1,
            EXTRACT(EPOCH FROM clock_timestamp())::integer
        );
    END IF;

    IF p_season = 0 THEN
        RETURN QUERY
        SELECT current_game."season",
               current_game."step"::integer,
               current_game."season_start_time",
               COALESCE((
                   SELECT MAX(result."prize_count")
                   FROM "world"."pledge_game_result" AS result
                   WHERE result."season" = current_game."season"
               ), 0),
               COALESCE(previous_game."winner_pledge_id", 0),
               COALESCE((
                   SELECT pledge."name"::text
                   FROM "world"."pledge" AS pledge
                   WHERE pledge."pledge_id" =
                       previous_game."winner_pledge_id"
               ), ''),
               COALESCE(previous_game."winner_char_id", 0),
               COALESCE((
                   SELECT character."char_name"::text
                   FROM "world"."user_data" AS character
                   WHERE character."char_id" =
                       previous_game."winner_char_id"
               ), ''),
               COALESCE(previous_game."winner_got_item", 0)::integer
        FROM "world"."pledge_game" AS current_game
        LEFT JOIN "world"."pledge_game" AS previous_game
          ON current_game."season" = previous_game."season" + 1
        WHERE current_game."step" < 2
        ORDER BY current_game."season" DESC
        LIMIT 1;
    ELSE
        RETURN QUERY
        SELECT current_game."season",
               current_game."step"::integer,
               current_game."season_start_time",
               COALESCE((
                   SELECT MAX(result."prize_count")
                   FROM "world"."pledge_game_result" AS result
                   WHERE result."season" = current_game."season"
               ), 0),
               COALESCE(previous_game."winner_pledge_id", 0),
               COALESCE((
                   SELECT pledge."name"::text
                   FROM "world"."pledge" AS pledge
                   WHERE pledge."pledge_id" =
                       previous_game."winner_pledge_id"
               ), ''),
               COALESCE(previous_game."winner_char_id", 0),
               COALESCE((
                   SELECT character."char_name"::text
                   FROM "world"."user_data" AS character
                   WHERE character."char_id" =
                       previous_game."winner_char_id"
               ), ''),
               COALESCE(previous_game."winner_got_item", 0)::integer
        FROM "world"."pledge_game" AS current_game
        LEFT JOIN "world"."pledge_game" AS previous_game
          ON current_game."season" = previous_game."season" + 1
        WHERE current_game."season" = p_season;
    END IF;
END;
$function$;

