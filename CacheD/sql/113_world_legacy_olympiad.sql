CREATE OR REPLACE FUNCTION "world"."lin_nominateheroes"(
    p_now_season integer,
    p_new_step integer,
    p_new_season_start_time integer
) RETURNS TABLE (
    new_season integer
)
LANGUAGE plpgsql
VOLATILE
AS $function$
DECLARE
    v_candidate_class integer;
    v_point_max integer;
    v_win_max integer;
    v_ratio_max double precision;
    v_team_win_max integer;
    v_count1 integer;
    v_count2 integer;
    v_count3 integer;
    v_count4 integer;
    v_total_participants integer;
    v_rank1 integer;
    v_rank2 integer;
    v_rank3 integer;
    v_rank4 integer;
    v_new_season integer;
BEGIN
    UPDATE "world"."user_nobless" SET "hero_type" = 0;

    CREATE TEMP TABLE IF NOT EXISTS "cached_olympiad_participant" (
        "char_id" integer,
        "main_class" integer,
        "match_count" integer,
        "olympiad_point" integer,
        "olympiad_win_count" integer,
        "win_ratio" double precision,
        "olympiad_lose_count" integer
    ) ON COMMIT DROP;
    TRUNCATE pg_temp."cached_olympiad_participant";

    CREATE TEMP TABLE IF NOT EXISTS "cached_hero_candidate" (
        "char_id" integer,
        "main_class" integer,
        "match_count" integer,
        "olympiad_point" integer,
        "olympiad_win_count" integer,
        "win_ratio" double precision,
        "olympiad_lose_count" integer,
        "team_win_count" integer,
        "ranking" integer
    ) ON COMMIT DROP;
    TRUNCATE pg_temp."cached_hero_candidate";

    CREATE TEMP TABLE IF NOT EXISTS "cached_highest_score" (
        "main_class" integer,
        "olympiad_point" integer,
        "match_count" integer,
        "olympiad_win_count" integer,
        "win_ratio" double precision
    ) ON COMMIT DROP;
    TRUNCATE pg_temp."cached_highest_score";

    CREATE TEMP TABLE IF NOT EXISTS "cached_highest_score_nobless" (
        "char_id" integer,
        "main_class" integer
    ) ON COMMIT DROP;
    TRUNCATE pg_temp."cached_highest_score_nobless";

    CREATE TEMP TABLE IF NOT EXISTS "cached_hero" (
        "char_id" integer,
        "main_class" integer
    ) ON COMMIT DROP;
    TRUNCATE pg_temp."cached_hero";

    INSERT INTO pg_temp."cached_olympiad_participant"
    SELECT nobless."char_id",
           character."subjob0_class",
           nobless."match_count",
           nobless."olympiad_point",
           nobless."olympiad_win_count",
           nobless."olympiad_win_count"::double precision /
               nobless."match_count"::double precision,
           nobless."olympiad_lose_count"
    FROM "world"."user_nobless" AS nobless
    JOIN "world"."user_data" AS character
      ON nobless."char_id" = character."char_id"
    WHERE nobless."match_count" >= 10
      AND (
          character."subjob0_class" BETWEEN 148 AND 181
          OR character."subjob0_class" BETWEEN 188 AND 189
      )
      AND character."account_id" > -1;

    INSERT INTO pg_temp."cached_hero_candidate"
    SELECT participant."char_id",
           participant."main_class",
           participant."match_count",
           participant."olympiad_point",
           participant."olympiad_win_count",
           participant."win_ratio",
           participant."olympiad_lose_count",
           0,
           ROW_NUMBER() OVER (
               ORDER BY participant."olympiad_point" DESC NULLS LAST,
                        participant."olympiad_win_count" DESC NULLS LAST,
                        participant."win_ratio" DESC NULLS LAST,
                        participant."match_count" DESC NULLS LAST,
                        character."exp" DESC NULLS LAST,
                        participant."char_id"
           )::integer
    FROM pg_temp."cached_olympiad_participant" AS participant
    JOIN "world"."user_data" AS character
      ON participant."char_id" = character."char_id";

    UPDATE pg_temp."cached_hero_candidate" AS candidate
    SET "team_win_count" = team_wins."win_count"
    FROM (
        SELECT match."char_id", COUNT(match."char_id")::integer AS "win_count"
        FROM "world"."olympiad_match" AS match
        WHERE match."game_rule" = 0
        GROUP BY match."char_id", match."game_rule"
    ) AS team_wins
    WHERE candidate."char_id" = team_wins."char_id";

    FOR v_candidate_class IN
        SELECT DISTINCT candidate."main_class"
        FROM pg_temp."cached_hero_candidate" AS candidate
    LOOP
        SELECT MAX(candidate."olympiad_point")
        INTO v_point_max
        FROM pg_temp."cached_hero_candidate" AS candidate
        WHERE candidate."main_class" = v_candidate_class;

        SELECT MAX(candidate."olympiad_win_count")
        INTO v_win_max
        FROM pg_temp."cached_hero_candidate" AS candidate
        WHERE candidate."main_class" = v_candidate_class
          AND candidate."olympiad_point" = v_point_max;

        SELECT MAX(candidate."win_ratio")
        INTO v_ratio_max
        FROM pg_temp."cached_hero_candidate" AS candidate
        WHERE candidate."main_class" = v_candidate_class
          AND candidate."olympiad_point" = v_point_max
          AND candidate."olympiad_win_count" = v_win_max;

        SELECT MAX(candidate."team_win_count")
        INTO v_team_win_max
        FROM pg_temp."cached_hero_candidate" AS candidate
        WHERE candidate."main_class" = v_candidate_class
          AND candidate."olympiad_point" = v_point_max
          AND candidate."olympiad_win_count" = v_win_max
          AND candidate."win_ratio" = v_ratio_max;

        SELECT COUNT(*)::integer INTO v_count1
        FROM pg_temp."cached_hero_candidate" AS candidate
        WHERE candidate."main_class" = v_candidate_class
          AND candidate."olympiad_point" = v_point_max;

        SELECT COUNT(*)::integer INTO v_count2
        FROM pg_temp."cached_hero_candidate" AS candidate
        WHERE candidate."main_class" = v_candidate_class
          AND candidate."olympiad_point" = v_point_max
          AND candidate."olympiad_win_count" = v_win_max;

        SELECT COUNT(*)::integer INTO v_count3
        FROM pg_temp."cached_hero_candidate" AS candidate
        WHERE candidate."main_class" = v_candidate_class
          AND candidate."olympiad_point" = v_point_max
          AND candidate."olympiad_win_count" = v_win_max
          AND candidate."win_ratio" = v_ratio_max;

        SELECT COUNT(*)::integer INTO v_count4
        FROM pg_temp."cached_hero_candidate" AS candidate
        WHERE candidate."main_class" = v_candidate_class
          AND candidate."olympiad_point" = v_point_max
          AND candidate."olympiad_win_count" = v_win_max
          AND candidate."win_ratio" = v_ratio_max
          AND candidate."team_win_count" = v_team_win_max;

        IF v_count1 = 1 THEN
            INSERT INTO pg_temp."cached_highest_score"
            SELECT candidate."main_class",
                   candidate."olympiad_point",
                   candidate."match_count",
                   candidate."olympiad_win_count",
                   candidate."win_ratio"
            FROM pg_temp."cached_hero_candidate" AS candidate
            WHERE candidate."main_class" = v_candidate_class
              AND candidate."olympiad_point" = v_point_max;
        ELSIF v_count2 = 1 THEN
            INSERT INTO pg_temp."cached_highest_score"
            SELECT candidate."main_class",
                   candidate."olympiad_point",
                   candidate."match_count",
                   candidate."olympiad_win_count",
                   candidate."win_ratio"
            FROM pg_temp."cached_hero_candidate" AS candidate
            WHERE candidate."main_class" = v_candidate_class
              AND candidate."olympiad_point" = v_point_max
              AND candidate."olympiad_win_count" = v_win_max;
        ELSIF v_count3 = 1 THEN
            INSERT INTO pg_temp."cached_highest_score"
            SELECT candidate."main_class",
                   candidate."olympiad_point",
                   candidate."match_count",
                   candidate."olympiad_win_count",
                   candidate."win_ratio"
            FROM pg_temp."cached_hero_candidate" AS candidate
            WHERE candidate."main_class" = v_candidate_class
              AND candidate."olympiad_point" = v_point_max
              AND candidate."olympiad_win_count" = v_win_max
              AND candidate."win_ratio" = v_ratio_max;
        ELSIF v_count4 = 1 THEN
            INSERT INTO pg_temp."cached_highest_score"
            SELECT candidate."main_class",
                   candidate."olympiad_point",
                   candidate."match_count",
                   candidate."olympiad_win_count",
                   candidate."win_ratio"
            FROM pg_temp."cached_hero_candidate" AS candidate
            WHERE candidate."main_class" = v_candidate_class
              AND candidate."olympiad_point" = v_point_max
              AND candidate."olympiad_win_count" = v_win_max
              AND candidate."win_ratio" = v_ratio_max
              AND candidate."team_win_count" = v_team_win_max;
        END IF;
    END LOOP;

    INSERT INTO pg_temp."cached_highest_score_nobless"
    SELECT candidate."char_id", candidate."main_class"
    FROM pg_temp."cached_hero_candidate" AS candidate
    JOIN pg_temp."cached_highest_score" AS score
      ON candidate."main_class" = score."main_class"
     AND candidate."olympiad_point" = score."olympiad_point"
     AND candidate."match_count" = score."match_count"
     AND candidate."olympiad_win_count" = score."olympiad_win_count"
     AND candidate."win_ratio" = score."win_ratio";

    INSERT INTO pg_temp."cached_hero"
    SELECT candidate."char_id", candidate."main_class"
    FROM pg_temp."cached_highest_score_nobless" AS candidate
    WHERE candidate."main_class" IN (
        SELECT grouped."main_class"
        FROM pg_temp."cached_highest_score_nobless" AS grouped
        GROUP BY grouped."main_class"
        HAVING COUNT(grouped."main_class") = 1
    );

    UPDATE "world"."user_nobless" AS nobless
    SET "hero_type" = 1,
        "win_count" = nobless."win_count" + 1
    WHERE nobless."char_id" IN (
        SELECT hero."char_id" FROM pg_temp."cached_hero" AS hero
    );

    UPDATE "world"."user_nobless" AS nobless
    SET "previous_point" = nobless."olympiad_point",
        "trade_point" = 0;

    SELECT MAX(candidate."ranking")
    INTO v_total_participants
    FROM pg_temp."cached_hero_candidate" AS candidate;

    v_rank1 := v_total_participants / 100;
    IF v_rank1 < 1 THEN v_rank1 := 1; END IF;
    v_rank2 := v_total_participants / 10;
    IF v_rank2 < 1 THEN v_rank2 := 1; END IF;
    v_rank3 := v_total_participants / 4;
    IF v_rank3 < 1 THEN v_rank3 := 1; END IF;
    v_rank4 := v_total_participants / 2;
    IF v_rank4 < 1 THEN v_rank4 := 1; END IF;

    UPDATE "world"."user_nobless" AS nobless
    SET "trade_point" = CASE
        WHEN candidate."ranking" <= v_rank1 THEN 60
        WHEN candidate."ranking" <= v_rank2 THEN 50
        WHEN candidate."ranking" <= v_rank3 THEN 45
        WHEN candidate."ranking" <= v_rank4 THEN 40
        ELSE 30
    END
    FROM pg_temp."cached_hero_candidate" AS candidate
    WHERE nobless."char_id" = candidate."char_id";

    UPDATE "world"."user_nobless" AS nobless
    SET "trade_point" = nobless."trade_point" + 10
    FROM pg_temp."cached_hero_candidate" AS candidate
    WHERE nobless."char_id" = candidate."char_id"
      AND nobless."olympiad_win_count" > 0;

    UPDATE "world"."user_nobless"
    SET "olympiad_point" = 0,
        "match_count" = 0,
        "olympiad_win_count" = 0,
        "olympiad_lose_count" = 0;

    INSERT INTO "world"."olympiad_result" (
        "season",
        "class",
        "char_id",
        "point",
        "match_count",
        "olympiad_win_count",
        "olympiad_lose_count",
        "team_win_count",
        "ranking"
    )
    SELECT p_now_season,
           candidate."main_class",
           candidate."char_id",
           candidate."olympiad_point",
           candidate."match_count",
           candidate."olympiad_win_count",
           candidate."olympiad_lose_count",
           candidate."team_win_count",
           candidate."ranking"
    FROM pg_temp."cached_hero_candidate" AS candidate;

    INSERT INTO "world"."olympiad" (
        "step",
        "season_start_time"
    ) VALUES (
        p_new_step,
        p_new_season_start_time
    ) RETURNING "season" INTO v_new_season;

    RETURN QUERY SELECT v_new_season;
END;
$function$;

