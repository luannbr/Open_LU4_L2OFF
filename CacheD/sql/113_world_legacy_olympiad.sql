    "is_winner" smallint,
    "elapsed_time" integer DEFAULT 0 NOT NULL,
    "game_rule" integer DEFAULT 0 NOT NULL,
    "match_id" integer GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    "step" integer,
    CONSTRAINT "ck_olympiad_match_is_winner_tinyint"
        CHECK ("is_winner" BETWEEN 0 AND 255),
    CONSTRAINT "pk_olympiad_match" PRIMARY KEY ("match_id")
);

CREATE INDEX IF NOT EXISTS "idx_olympiad_match_match_time"
    ON "world"."olympiad_match" ("match_time");
CREATE INDEX IF NOT EXISTS "idx_olympiad_match_season_char_id"
