            UPDATE "world"."user_nobless" AS nobless
            SET "olympiad_point" = 0
            WHERE nobless."char_id" = p_winner_id
              AND nobless."olympiad_point" < 0;
            SELECT character."subjob0_class"
            INTO v_winner_class
            FROM "world"."user_data" AS character
            WHERE character."char_id" = p_winner_id;
            INSERT INTO "world"."olympiad_match" (
                "season", "step", "class", "match_time", "char_id",
                "rival_id", "point", "is_winner", "elapsed_time", "game_rule"
            ) VALUES (
                p_season, p_step, v_winner_class, p_time, p_winner_id,
                p_loser_id, p_winner_point, 1, p_elapsed_time, p_game_rule
            );
        END IF;

        IF p_loser_id <> 0 THEN
            UPDATE "world"."user_nobless" AS nobless
            SET "olympiad_point" = nobless."olympiad_point" + p_loser_point,
                "match_count" = nobless."match_count" + 1,
                "olympiad_lose_count" = nobless."olympiad_lose_count" + 1
