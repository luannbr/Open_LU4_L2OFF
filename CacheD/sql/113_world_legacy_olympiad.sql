CREATE SCHEMA IF NOT EXISTS "world";

-- This current world table was absent from the earlier mechanical stable-table
-- export. Classic 3.0, Ertheia and modified 287 agree on every named column,
-- type and constraint. Modified 287 only swaps the physical numbers of
-- elapsed_time and game_rule. Every current-compatible body addresses those
-- columns by name, so the shared Classic/Ertheia order is the main
-- portable layout without claiming an unobservable current MSSQL number.
-- lin_SaveOlympiadRecord and lin_NominateHeroes prove the live dependencies.
