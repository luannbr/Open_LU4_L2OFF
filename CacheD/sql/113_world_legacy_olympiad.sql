CREATE OR REPLACE FUNCTION "world"."lin_initallolympiadpoint"(
    p_season integer,
    p_step integer,
    p_init_point integer
) RETURNS void
LANGUAGE plpgsql
VOLATILE
AS $function$
BEGIN
    UPDATE "world"."user_nobless" AS nobless
    SET "olympiad_point" = p_init_point
    WHERE nobless."char_id" IN (
        SELECT character."char_id"
        FROM "world"."user_data" AS character
        LEFT JOIN "world"."user_subjob" AS subjob
          ON character."char_id" = subjob."char_id"
         AND subjob."subjob_id" = 0
        WHERE (
            COALESCE(character."subjob_id", 0) = 0
            AND character."subjob0_class" > 138
            AND character."lev" >= 85
        ) OR (
            COALESCE(character."subjob_id", 0) > 0
            AND character."subjob0_class" > 138
            AND subjob."level" >= 85
        )
    );

    UPDATE "world"."olympiad" AS olympiad
    SET "step" = p_step
    WHERE olympiad."season" = p_season;
END;
$function$;

