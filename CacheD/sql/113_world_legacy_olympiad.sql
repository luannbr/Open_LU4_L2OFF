CREATE OR REPLACE FUNCTION "world"."lin_modolympiadpoint"(
    p_char_id integer,
    p_previous_point integer,
    p_olympiad_point integer,
    p_mod_type integer
) RETURNS void
LANGUAGE plpgsql
VOLATILE
AS $function$
DECLARE
    v_previous_point integer;
    v_olympiad_point integer;
BEGIN
    SELECT nobless."previous_point",
           nobless."olympiad_point"
    INTO v_previous_point,
         v_olympiad_point
    FROM "world"."user_nobless" AS nobless
    WHERE nobless."char_id" = p_char_id;

    IF NOT FOUND OR
       v_previous_point IS NULL OR
       v_olympiad_point IS NULL THEN
        RETURN;
    END IF;

    IF p_mod_type = 1 THEN
        v_previous_point = GREATEST(
            v_previous_point + p_previous_point,
            0);
        v_olympiad_point = GREATEST(
            v_olympiad_point + p_olympiad_point,
            0);
    ELSE
        v_previous_point = GREATEST(p_previous_point, 0);
        v_olympiad_point = GREATEST(p_olympiad_point, 0);
    END IF;

    UPDATE "world"."user_nobless" AS nobless
    SET "previous_point" = v_previous_point,
        "olympiad_point" = v_olympiad_point
    WHERE nobless."char_id" = p_char_id;
END;
$function$;

